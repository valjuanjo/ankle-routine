#!/usr/bin/env node
// Inlines content/*.json into prototype/content.js so the prototype opens from a file or any static host.
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('..', import.meta.url).pathname;
const files = ['exercises', 'programs', 'team-warmup', 'safety-checklist', 'intended-use'];
const content = Object.fromEntries(files.map((f) => [f, JSON.parse(readFileSync(`${root}content/${f}.json`, 'utf8'))]));
writeFileSync(`${root}prototype/content.js`, `// Generated by scripts/build-prototype.mjs. Do not edit.\nwindow.CONTENT = ${JSON.stringify(content)};\n`);
console.log('prototype/content.js');
